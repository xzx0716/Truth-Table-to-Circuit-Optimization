#!/usr/bin/env python3
"""Export the same project sources as one dependency-free C++17 translation unit."""
import argparse
import hashlib
import json
import re
from pathlib import Path


def export(root, output):
    seen = set()
    sources = {}
    pattern = re.compile(r'^\s*#\s*include\s*"(ttc/[^"\n]+)"\s*$')

    def inline(path):
        path = path.resolve()
        if not path.is_relative_to(root):
            raise ValueError(f"include outside project: {path}")
        if path in seen:
            return ""
        seen.add(path)
        relative = path.relative_to(root).as_posix()
        raw = path.read_bytes()
        sources[relative] = hashlib.sha256(raw).hexdigest()
        lines = [f"\n// BEGIN {relative}\n"]
        for line in raw.decode("utf-8-sig").splitlines(keepends=True):
            match = pattern.match(line.rstrip("\r\n"))
            if match:
                lines.append(inline(root / "include" / match.group(1)))
            elif re.match(r'^\s*#\s*pragma\s+once\s*$', line):
                continue
            elif re.match(r'^\s*#\s*include\s*"', line):
                raise ValueError(f"unsupported quoted include in {relative}: {line.strip()}")
            else:
                lines.append(line)
        lines.append(f"\n// END {relative}\n")
        return "".join(lines)

    # Headers encountered from main carry declarations. Implementations may follow main.
    code = "// Generated by tools/export_submission.py. Edit src/ and include/, not this file.\n"
    code += inline(root / "src/main.cpp")
    for path in sorted((root / "src").rglob("*.cpp")):
        if path != root / "src/main.cpp":
            code += inline(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(code, encoding="utf-8", newline="\n")
    manifest = {"export_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
                "sources": sources,
                "compile": "g++ -O2 -std=c++17 solver.cpp -o solver"}
    output.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, default=Path("dist/solver.cpp"))
    args = parser.parse_args()
    print(json.dumps(export(args.root.resolve(), args.output.resolve()), indent=2))
