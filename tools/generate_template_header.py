#!/usr/bin/env python3
"""Convert verified generic exact candidates to a dependency-free C++ library.

Input solver uses MSB-first variables. Header truth signatures use LSB boundary0,
matching the production cut implementation. IDs retain 1=input0 and 2=input1.
"""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OPS={'AND2':0,'OR2':1,'NOT':2}

def parse_and_verify(record):
    lines=record['netlist'].strip().splitlines()
    gates=[]
    for signal,line in enumerate(lines[:-1],3):
        w=line.split();i=int(w[0]);op=OPS[w[1]];a=int(w[2]);b=int(w[3]) if op!=2 else 0
        assert i==signal and 0<=a<i and 0<=b<i
        gates.append((op,a,b))
    output=int(lines[-1]);assert 0<=output<3+len(gates)
    # Template IDs input1/input2 retain original function variable order; only
    # truth-table enumeration changes from MSB-first to LSB boundary0.
    pattern=0
    for row in range(4):
        values=[0,row&1,(row>>1)&1]
        for op,a,b in gates:values.append(values[a]&values[b] if op==0 else values[a]|values[b] if op==1 else 1-values[a])
        source_row=((row&1)<<1)|((row>>1)&1)
        assert values[output]==record['truth'][source_row]
        pattern|=values[output]<<row
    return pattern,tuple(gates),output

def generate(source,output):
    source_bytes=source.read_bytes();data=json.loads(source_bytes);seen=set();templates=[]
    for record in data['records']:
        if 'netlist' not in record:continue
        entry=parse_and_verify(record)
        if entry in seen:continue
        seen.add(entry);templates.append(entry)
    # Exact unit-cost optima alone omit slower/cheaper implementations under
    # other gate prices. Add universally equivalent De Morgan variants; these
    # are candidates, not additional optimality claims.
    originals=list(templates)
    for pattern,gates,out in originals:
        for replace_op in (0,1):
            result=[]; ids={0:0,1:1,2:2}; cache={}; negatives={}
            def raw(op,a,b=0):
                if op!=2 and b<a:a,b=b,a
                key=(op,a,b)
                if key not in cache:
                    cache[key]=3+len(result);result.append(key)
                return cache[key]
            def inv(a):
                if a not in negatives:
                    b=raw(2,a);negatives[a]=b;negatives[b]=a
                return negatives[a]
            for i,(op,a,b) in enumerate(gates,3):
                a=ids[a];b=ids[b]
                if op==2:ids[i]=inv(a)
                elif op==replace_op:ids[i]=inv(raw(1-op,inv(a),inv(b)))
                else:ids[i]=raw(op,a,b)
            variant=(pattern,tuple(result),ids[out])
            if variant not in seen:seen.add(variant);templates.append(variant)
    # Check added candidates as well as the solver records.
    for pattern,gates,out in templates:
        for row in range(4):
            values=[0,row&1,(row>>1)&1]
            for op,a,b in gates:values.append(values[a]&values[b] if op==0 else values[a]|values[b] if op==1 else 1-values[a])
            assert values[out]==((pattern>>row)&1)
    templates.sort()
    assert {x[0] for x in templates}==set(range(16))
    lines=['// Generated by tools/generate_template_header.py; do not hand edit.',
           '// Generic functions only: no public case answer data.',
           '// Truth signature: bit row, row bit0=input signal1, row bit1=input signal2.',
           '// Source JSON SHA-256: '+hashlib.sha256(source_bytes).hexdigest(),
           '#pragma once','#include <vector>','namespace ttc {',
           'struct TemplateGate { int op, a, b; };',
           'struct ExactTemplate { unsigned truth; std::vector<TemplateGate> gates; int output; };',
           'inline const std::vector<ExactTemplate>& exact_templates() {',
           '    static const std::vector<ExactTemplate> templates{']
    for truth,gates,out in templates:
        gs=', '.join('{%d,%d,%d}'%g for g in gates)
        lines.append('        {%du, {%s}, %d},'%(truth,gs,out))
    lines+=['    };','    return templates;','}','} // namespace ttc','']
    output.parent.mkdir(parents=True,exist_ok=True);output.write_text('\n'.join(lines))
    return templates

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--input',type=Path,default=ROOT/'research/exact/generic_templates.json');ap.add_argument('--output',type=Path,default=ROOT/'include/ttc/generated_templates.hpp');args=ap.parse_args()
    templates=generate(args.input,args.output)
    print('verified',len(templates),'distinct templates covering all 16 two-input functions')
if __name__=='__main__':main()
